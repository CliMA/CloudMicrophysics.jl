# The condensation self-derivative: `docs/src/RosenbrockNumerics.md`'s one directly
# measured entry, "a ratio of 1.0, to four significant figures, at every state" of this
# same twenty-state corpus.
const CONDENSATION_SELF_DERIVATIVE = (1, 1)
const CONDENSATION_SELF_DERIVATIVE_RTOL = 1.0e-4

function mp_and_tps(::Type{FT}) where {FT}
    mp = CMP.Microphysics2MParams(
        FT; with_ice = true, is_limited = true, aerosol = CMP.PrescribedAerosol(FT),
    )
    tps = TDI.TD.Parameters.ThermodynamicsParameters(FT)
    return mp, tps
end

@testset "p3_2m_process_rates slot names and order" begin
    FT = Float64
    mp, tps = mp_and_tps(FT)
    row = CORPUS[6]  # a mixed-phase row, so every slot the docstring names is exercised
