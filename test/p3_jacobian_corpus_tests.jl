# A1: the AD-vs-manual 2M+P3 Jacobian corpus battery.
#
# Compares `ManualJacobian` (`_jacobian_2mp3_manual`, `_jacobian_2mp3t_manual`) against
# `ExactJacobian` (`ForwardDiff`) at a fixed corpus of physically realized states, for
# both the eight-species substep state and the temperature-coupled nine-vector.
#
# WHAT THIS FILE VERIFIES WITH A NUMERIC TOLERANCE, and where the tolerance comes from:
#   - The condensation self-derivative (the `(q_lcl, q_lcl)` entry) agrees with the AD
#     reference to a ratio of 1.0 at four significant figures, at every corpus state.
#     This is the one entry `docs/src/RosenbrockNumerics.md` ("Numerical verification")
#     measures directly, and the number this file locks (`rtol = 1e-4`) is that
#     document's own figure.
#   - The temperature-coupled state's structural identities (`Ṫ = cᵀf`, the temperature
#     row `cᵀf_q`, the temperature corner `cᵀf_T`, and the species block matching
#     `ManualJacobian`'s own output) are the same page's "by construction" claims; the
#     tolerances here are the same order as the ones quoted there (`1e-14`, `~1e-9`,
#     `~1e-11`, exact at `Float64`) but loosened by one to three orders as a margin
#     against implementation details this file did not itself measure.
#
# WHAT THIS FILE DOES NOT VERIFY NUMERICALLY: every other Jacobian entry is a mix of
# closed-form (Tier 1) and donor-linearized (Tier 2/3) contributions accumulated into
# the same matrix cell (see the tier commentary on `_jacobian_2mp3_manual`), so no
# single tolerance describes it and none is documented. Those entries are asserted
# finite at both precisions only - which is the corpus's other job, exercising the
# `logλ = -Inf` and near-zero-population rows without producing non-finite output - not
# checked against the AD reference. Locking real per-entry tolerances for them needs a
# run on a compute node against this corpus, which this environment does not have.
#
# The 31 entries `_jacobian_2mp3_manual` never assembles (the corresponding keyword of
# `_jacobian_2mp3` is not passed at its call site, so the entry is exactly that
# keyword's `zero(FT)` default at every state, provable from the source rather than
# measured) are asserted exactly zero on the manual side and excluded from the AD
# comparison entirely: they are documented Tier-2/3 omissions (donor-linearized
# couplings the manual matrix does not carry), not places where the true derivative is
# zero, so comparing them against a nonzero AD entry would be asserting the wrong thing.

