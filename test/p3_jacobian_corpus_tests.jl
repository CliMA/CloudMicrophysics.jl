    )
    @test length(pp) == 21
    # the parts-sum-to-total identity holds by construction; assert it directly rather
    # than trusting the construction
    g = BMT.Instantaneous2MP3Tendency(
        mp, tps, FT(row.ρ), FT(row.T), FT(row.q_tot), FT(row.logλ), FT(row.w), FT(row.p),
    )
    x8 = BMT.MicroState2MP3{FT}(
