        q_tot = FT(row.q_tot), q_lcl = FT(row.q_lcl), n_lcl = FT(row.n_lcl),
        q_rai = FT(row.q_rai), n_rai = FT(row.n_rai), q_ice = FT(row.q_ice),
        n_ice = FT(row.n_ice), q_rim = FT(row.q_rim), b_rim = FT(row.b_rim),
    )
    thermo = (; ρ = FT(row.ρ), T = FT(row.T), w = FT(row.w), p = FT(row.p), logλ = FT(row.logλ))
    pp, rs = BMT.p3_2m_process_rates(mp, tps, micro, thermo)
    @test keys(pp) == (
