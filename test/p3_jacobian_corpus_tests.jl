                for r in 1:8, c in 1:8
                    (r, c) in zeros_set && continue
                    @test isfinite(J_manual[r, c])
                    @test isfinite(J_exact[r, c])
                end
            end
        end
    end

    @testset "A1 Jacobian corpus, temperature-coupled nine-vector ($FT)" begin
        for (i, row) in enumerate(CORPUS)
            x8 = BMT.MicroState2MP3{FT}(
                FT(row.q_lcl), FT(row.n_lcl), FT(row.q_rai), FT(row.n_rai),
                FT(row.q_ice), FT(row.n_ice), FT(row.q_rim), FT(row.b_rim),
            )
            g8 = BMT.Instantaneous2MP3Tendency(
                mp, tps, FT(row.ρ), FT(row.T), FT(row.q_tot), FT(row.logλ), FT(row.w), FT(row.p),
            )
            _, J_manual8 = BMT._tendency_and_jacobian(BMT.ManualJacobian(), g8, x8)

            y9 = BMT.MicroState2MP3T{FT}(
                FT(row.q_lcl), FT(row.n_lcl), FT(row.q_rai), FT(row.n_rai),
                FT(row.q_ice), FT(row.n_ice), FT(row.q_rim), FT(row.b_rim), FT(row.T),
            )
            g9 = BMT.Temperature2MP3Tendency(
                mp, tps, FT(row.ρ), FT(row.q_tot), FT(row.logλ), FT(row.w), FT(row.p),
            )
            f_manual9, J_manual9 = BMT._tendency_and_jacobian(BMT.TemperatureCoupledJacobian(), g9, y9)
            f_exact9, J_exact9 = BMT._tendency_and_jacobian(BMT.ExactJacobian(), g9, y9)

            @testset "state $i" begin
                @test all(isfinite, f_manual9)
                @test all(isfinite, f_exact9)
                @test all(isapprox.(f_manual9, f_exact9; rtol = FT(1.0e-6), atol = eps(FT)))

                # Ṫ = cᵀf: the temperature-coupled tendency's own ninth slot IS the latent
                # heating of its own species slots, `_temperature_2mp3_tendency`'s literal
                # construction (`docs/src/RosenbrockNumerics.md`: agree to 1e-14 at a
                # representative state; loosened here as this file's own margin).
                Lv = TDI.Lᵥ(tps, FT(row.T))
                Ls = TDI.Lₛ(tps, FT(row.T))
                cp_air = TDI.cpₘ(tps, FT(row.q_tot), FT(row.q_lcl) + FT(row.q_rai), FT(row.q_ice))
                cTf = (Lv * (f_manual9[1] + f_manual9[3]) + Ls * f_manual9[5]) / cp_air
                @test isapprox(f_manual9[9], cTf; rtol = FT(1.0e-10))

                # the species block is `_jacobian_2mp3_manual`'s own output at the same
                # state ("J9's species block matches ManualJacobian's output exactly at
                # Float64, and to within 28 units in the last place at Float32")
                if FT == Float64
                    @test J_manual9[1:8, 1:8] == J_manual8
                else
                    @test all(isapprox.(J_manual9[1:8, 1:8], J_manual8; rtol = FT(1.0e-5)))
                end

                # the temperature row is cᵀf_q and the corner is cᵀf_T, reconstructed
                # independently from the returned species block rather than trusted
                row9_from_block =
                    (Lv .* (J_manual9[1, 1:8] .+ J_manual9[3, 1:8]) .+ Ls .* J_manual9[5, 1:8]) ./
                    cp_air
                @test all(isapprox.(J_manual9[9, 1:8], row9_from_block; rtol = FT(1.0e-8)))
                corner_from_col =
                    (Lv * (J_manual9[1, 9] + J_manual9[3, 9]) + Ls * J_manual9[5, 9]) / cp_air
                @test isapprox(J_manual9[9, 9], corner_from_col; rtol = FT(1.0e-8))

                (r, c) = CONDENSATION_SELF_DERIVATIVE
                @test isapprox(
                    J_manual9[r, c], J_exact9[r, c]; rtol = FT(CONDENSATION_SELF_DERIVATIVE_RTOL),
                )

                zeros9 = Set(vcat(STRUCTURAL_ZERO_8x8, STRUCTURAL_ZERO_EXTRA_9x9))
                for (r, c) in zeros9
                    @test J_manual9[r, c] == zero(FT)
                end
                for r in 1:9, c in 1:9
                    (r, c) in zeros9 && continue
                    @test isfinite(J_manual9[r, c])
                    @test isfinite(J_exact9[r, c])
                end
            end
        end
    end
